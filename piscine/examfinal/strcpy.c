char    *ft_strcpy(char *s1, char *s2)
{
	int i;
	i = 0;
	while (s2[i])
	{
		s1[i] = s2[i];
		i++;
	}
	s1[i] = '\0'; //ここ忘れないように！最後終端文字！！
	return s1;
}
