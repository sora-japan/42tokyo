#include <unistd.h>

int	main(int argc, char **argv)
{
	if (argc != 3)
	{
		write(1, "\n", 1);
		return (0);
	}
	// すでに出力した文字を記録するフラグ
	// ASCIIの最大値である256要素を確保
	int used[256];
	int	i = 0;
	while (i < 256)
	{
		used[i] = 0;
		i++;
	}
	int	j = 1; // argv[1] , argv[2] を順に処理
	while (j <= 2)
	{
		int	k = 0;
		while (argv[j][k] != '\0')
		{
			//文字を数値(インデックス)として取得
			unsigned char c = (unsigned char)argv[j][k];
			// まだ出力されていない文字であれば出力し、フラグを立てる
			if (used[c] == 0)
			{
				write(1, &c, 1);//箱に入れずに出力
				used[c] = 1;
			}
			k++;
		}
		j++;
	}
	write(1, "\n", 1);
	return (0);
}

//コードの解説
//引数のチェック (argc != 3):
//コマンドライン引数は argv[0] がプログラム名、argv[1] と argv[2] が与えられた文字列になります。そのため、個数が3でない場合はエラー条件として改行を出力して終了します。
//
//重複チェック用の配列 (used[256]):
//「すでに表示したか」を覚えておくためのメモリです。各文字のASCIIコードに対応するインデックスを 1 に書き換えることで、2回目以降に同じ文字が出てきても無視できるようにします。
//
//2つの文字列を順番にスキャン:
//最初の while ループで argv[1]、次のループで argv[2] を処理します。これにより、「出現した順番通り」という条件を満たせます。
//
//unsigned char の使用:
//文字を配列の添字（インデックス）にする際、負の値にならないよう unsigned でキャストするのが安全な作法です。
//
//実行例の確認
//入力が ./a.out aabc can の場合：
//
//aabc を走査
//
//a: 初めてなので出力、used['a'] = 1
//
//a: すでに used['a'] は 1 なのでスルー
//
//b: 初めてなので出力、used['b'] = 1
//
//c: 初めてなので出力、used['c'] = 1
//
//can を走査
//
//c: すでに 1 なのでスルー
//
//a: すでに 1 なのでスルー
//
//n: 初めてなので出力、used['n'] = 1
//
//結果：abcn（＋改行）
